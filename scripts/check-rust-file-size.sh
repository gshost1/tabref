#!/usr/bin/env bash
#
# Enforces the two source-shape rules no compiler checks: at most 400 lines
# per .rs file, and no non-doc comments. Ported from agent-desktop.
#
# The comment half needs Python 3, found by probing python3, python and py,
# because Windows has no python3. A missing interpreter fails the gate rather
# than skipping it, and a self-test drives both rules before the tree scan, so
# a rule that stops detecting anything fails instead of passing in silence.

set -euo pipefail

cd "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

limit=400

# awk counts records, so an unterminated last line still counts. A file with
# an @generated marker in its first five lines reports -1 and is exempt.
oversize_report() {
    local file="$1"
    local lines
    lines="$(
        awk '
            NR <= 5 && index($0, "@generated") { generated = 1 }
            END { print (generated ? -1 : NR) }
        ' "$file"
    )"
    if [ "$lines" -gt "$limit" ]; then
        printf '%s: %s lines (limit %s)\n' "$file" "$lines" "$limit"
        return 1
    fi
    return 0
}

INTERPRETER_CANDIDATES=(python3 python py)

resolve_interpreter() {
    local candidate
    for candidate in "${INTERPRETER_CANDIDATES[@]}"; do
        if command -v "$candidate" >/dev/null 2>&1 &&
            "$candidate" -c 'import sys; raise SystemExit(0 if sys.version_info[0] >= 3 else 1)' \
                >/dev/null 2>&1; then
            printf '%s\n' "$candidate"
            return 0
        fi
    done
    return 1
}

require_interpreter() {
    local found
    if ! found="$(resolve_interpreter)"; then
        printf 'no working Python 3 interpreter on PATH (tried python3, python, py)\n' >&2
        return 1
    fi
    printf '%s\n' "$found"
}

rust_lines() {
    awk -v count="$1" 'BEGIN { for (i = 1; i <= count; i++) print "fn line() {}" }'
}

self_test() {
    local failures interpreter
    failures=0

    if oversize_report <(rust_lines "$((limit + 1))") >/dev/null 2>&1; then
        printf 'self-test FAIL (missed): a %s-line file did not trip the cap\n' "$((limit + 1))" >&2
        failures=1
    fi
    if oversize_report <(
        rust_lines "$limit"
        printf 'fn unterminated_last_line() {}'
    ) >/dev/null 2>&1; then
        printf 'self-test FAIL (missed): an unterminated last line was not counted\n' >&2
        failures=1
    fi
    if ! oversize_report <(rust_lines "$limit") >/dev/null 2>&1; then
        printf 'self-test FAIL (false positive): a %s-line file tripped the cap\n' "$limit" >&2
        failures=1
    fi
    if ! oversize_report <(
        printf '// @generated by a tool\n'
        rust_lines "$((limit + 1))"
    ) >/dev/null 2>&1; then
        printf 'self-test FAIL (false positive): an @generated file tripped the cap\n' >&2
        failures=1
    fi
    if (
        INTERPRETER_CANDIDATES=(tabref-no-such-interpreter)
        require_interpreter
    ) >/dev/null 2>&1; then
        printf 'self-test FAIL: the interpreter probe passed with no candidate\n' >&2
        failures=1
    fi
    if (
        INTERPRETER_CANDIDATES=(false)
        require_interpreter
    ) >/dev/null 2>&1; then
        printf 'self-test FAIL: the interpreter probe accepted a command that is not Python 3\n' >&2
        failures=1
    fi
    if interpreter="$(resolve_interpreter)"; then
        if ! "$interpreter" scripts/check_rust_comments_test.py >/dev/null 2>&1; then
            printf 'self-test FAIL: the comment scanner does not pass its own fixtures\n' >&2
            printf '  rerun for detail: %s scripts/check_rust_comments_test.py\n' "$interpreter" >&2
            failures=1
        fi
    fi

    if [ "$failures" -ne 0 ]; then
        printf 'The Rust source-shape rules do not behave as documented.\n' >&2
        return 1
    fi
    return 0
}

failed=0

self_test || failed=1

while IFS= read -r file; do
    [ -f "$file" ] || continue
    oversize_report "$file" >&2 || failed=1
done < <(git ls-files --cached --others --exclude-standard -- '*.rs')

if interpreter="$(require_interpreter)"; then
    if ! git ls-files -z --cached --others --exclude-standard -- '*.rs' |
        "$interpreter" scripts/check_rust_comments.py; then
        failed=1
    fi
else
    failed=1
fi

if [ "$failed" -ne 0 ]; then
    exit 1
fi
